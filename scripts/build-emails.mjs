// Compiles the email pieces in scripts/email-source.js to HTML and writes emails/compiled.js,
// so the wrappers never run mjml (which can't load in a Cloudflare Worker).
//
//   node scripts/build-emails.mjs           rewrite emails/compiled.js
//   node scripts/build-emails.mjs --check   fail if emails/compiled.js is out of date
//
// Each piece is compiled inside a probe document, between two mj-raw markers, and cut out.
// [[slot]] becomes <mj-raw>{{slot}}</mj-raw> so mjml passes it through untouched.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import mjml2html from "mjml";

import { SOURCE } from "./email-source.js";

const OUT = fileURLToPath(new URL("../emails/compiled.js", import.meta.url));
const BEGIN = "%%PIECE-BEGIN%%";
const END = "%%PIECE-END%%";

const rawSlots = (mjml) => mjml.replace(/\[\[(\w+)\]\]/g, "<mj-raw>{{$1}}</mj-raw>");
const marked = (mjml) => `<mj-raw>${BEGIN}</mj-raw>${rawSlots(mjml)}<mj-raw>${END}</mj-raw>`;

const DOCUMENT = rawSlots(SOURCE.document.mjml);
const inBody = (mjml) =>
  DOCUMENT.replace("<mj-raw>{{body}}</mj-raw>", mjml).replace("<mj-raw>{{support}}</mj-raw>", "");
const inCard = (mjml) => inBody(rawSlots(SOURCE.cardUnderLogo.mjml).replace("<mj-raw>{{children}}</mj-raw>", mjml));

function compile(mjml) {
  const { html, errors } = mjml2html(mjml, { validationLevel: "strict", minify: false });
  if (errors.length > 0) {
    throw new Error(`MJML compile failed:\n${errors.map((e) => e.formattedMessage).join("\n")}`);
  }
  return html;
}

function cut(html) {
  const start = html.indexOf(BEGIN);
  const end = html.indexOf(END);
  if (start < 0 || end < start) throw new Error("piece markers missing from compiled HTML");
  return html.slice(start + BEGIN.length, end);
}

// The document's font links depend on the body, so they become a {{fonts}} slot.
const FONT_LINKS = /<!--\[if !mso\]><!-->\s*<link [\s\S]*?<!--<!\[endif\]-->/g;

function compileDocument() {
  const html = compile(DOCUMENT);
  if (html.match(FONT_LINKS)?.length !== 1) throw new Error("font links not found in the document");
  return html.replace(FONT_LINKS, "{{fonts}}");
}

// A piece has a level; a plain object groups variants (severityStrip.info …).
function compilePiece(entry) {
  const { level, mjml } = entry;
  if (!level) return Object.fromEntries(Object.entries(entry).map(([k, v]) => [k, compilePiece(v)]));
  if (level === "document") return compileDocument();
  if (level === "section") return cut(compile(inBody(marked(mjml))));
  if (level === "column") return cut(compile(inCard(marked(mjml))));
  throw new Error(`unknown piece level "${level}"`);
}

const entries = Object.entries(SOURCE).map(
  ([name, piece]) => `  ${name}: ${JSON.stringify(compilePiece(piece))},`,
);
const output = `// Generated by \`npm run build:emails\` from scripts/email-source.js. Do not edit.
export const PIECES = Object.freeze({
${entries.join("\n")}
});
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (current !== output) {
    console.error("emails/compiled.js is out of date: run `npm run build:emails`.");
    process.exit(1);
  }
  console.log("emails/compiled.js is up to date.");
} else {
  writeFileSync(OUT, output);
  console.log(`wrote ${OUT}`);
}
