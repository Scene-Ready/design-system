#!/usr/bin/env node
// Regenerates fonts/: the self-hosted Barlow, Barlow Condensed and JetBrains Mono
// files every Scene Ready app serves, so no app loads fonts from Google.
//
// Usage: node scripts/vendor-fonts.mjs
//
// Pulls the pinned Fontsource packages with `npm pack` (no install), copies the
// latin and latin-ext woff2 files for the weights below, writes fonts/fonts.css
// with relative URLs, and copies each family's OFL licence. Run it after changing
// FAMILIES, then commit fonts/.
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// The union of the weights the apps use. A browser downloads a weight only when a
// page renders text in it, so an unused weight costs nothing at runtime.
// family must match the names in tokens.css (--font-sans, --font-condensed, --font-mono).
const FAMILIES = [
  { pkg: "@fontsource/barlow", version: "5.3.0", slug: "barlow", family: "Barlow", weights: [400, 500, 600, 700, 800] },
  {
    pkg: "@fontsource/barlow-condensed",
    version: "5.3.0",
    slug: "barlow-condensed",
    family: "Barlow Condensed",
    weights: [400, 500, 600, 700],
  },
  { pkg: "@fontsource/jetbrains-mono", version: "5.3.0", slug: "jetbrains-mono", family: "JetBrains Mono", weights: [400, 500] },
];
// latin-ext is only downloaded when a page has a character outside latin
// (unicode-range), so names like "Łukasz" render in the brand face.
const SUBSETS = ["latin-ext", "latin"];

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "fonts");
const work = mkdtempSync(join(tmpdir(), "sr-fonts-"));
rmSync(out, { recursive: true, force: true });
mkdirSync(out);

const rules = [];
for (const fam of FAMILIES) {
  const tgz = execFileSync("npm", ["pack", `${fam.pkg}@${fam.version}`, "--silent"], { cwd: work, encoding: "utf8" }).trim();
  const dir = join(work, fam.slug);
  mkdirSync(dir);
  execFileSync("tar", ["-xzf", join(work, tgz), "-C", dir]);
  const pkgDir = join(dir, "package");
  copyFileSync(join(pkgDir, "LICENSE"), join(out, `${fam.slug}-OFL.txt`));
  // Fontsource's per-subset CSS files carry no unicode-range; without one the
  // last-declared subset would win for every character, so add it from unicode.json.
  const ranges = JSON.parse(readFileSync(join(pkgDir, "unicode.json"), "utf8"));

  for (const weight of fam.weights) {
    for (const subset of SUBSETS) {
      const file = `${fam.slug}-${subset}-${weight}-normal.woff2`;
      copyFileSync(join(pkgDir, "files", file), join(out, file));
      // woff2 only: every browser the apps support has it.
      rules.push(
        [
          `/* ${fam.slug}-${subset}-${weight}-normal */`,
          "@font-face {",
          `  font-family: '${fam.family}';`,
          "  font-style: normal;",
          "  font-display: swap;",
          `  font-weight: ${weight};`,
          `  src: url(./${file}) format('woff2');`,
          `  unicode-range: ${ranges[subset]};`,
          "}",
        ].join("\n"),
      );
    }
  }
}
rmSync(work, { recursive: true, force: true });

const header = `/*
 * Scene Ready fonts, self-hosted. Generated by scripts/vendor-fonts.mjs; don't edit.
 * ${FAMILIES.map((f) => `${f.pkg}@${f.version}`).join(", ")} (SIL OFL 1.1, see *-OFL.txt).
 *
 * URLs are relative, so this file works both copied to /fonts/ by
 * scene-ready-brand-assets and imported through a bundler.
 */
`;
writeFileSync(join(out, "fonts.css"), `${header}\n${rules.join("\n\n")}\n`);
console.log(`vendor-fonts: wrote ${rules.length} @font-face rules to ${out}`);
